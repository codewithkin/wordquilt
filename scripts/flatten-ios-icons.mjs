#!/usr/bin/env node
/**
 * scripts/flatten-ios-icons.mjs — strip alpha from the iOS icons that
 * `expo prebuild` generates.
 *
 * ── Why this exists ─────────────────────────────────────────────────────────
 * App Store Connect rejects an app icon that carries an alpha channel, even a
 * fully-opaque one. Our SOURCE icons are correct — `assets/images/icon-ios*.png`
 * are all 8-bit RGB with no channel, and `scripts/check-assets.mjs` enforces
 * that. But `expo prebuild` re-encodes them into
 * `ios/<App>/Images.xcassets/AppIcon.appiconset/`, and as of Expo SDK 57 the
 * DARK variant comes out RGBA. Measured, not assumed:
 *
 *   App-Icon-1024x1024@1x.png         RGB   <- fine
 *   App-Icon-dark-1024x1024@1x.png    RGBA  <- rejected by App Store Connect
 *   App-Icon-tinted-1024x1024@1x.png  RGB   <- fine
 *
 * The asset README warned about exactly this: "Do not add alpha to the iOS
 * icons — App Store Connect rejects them and Expo will not strip it for you."
 *
 * Since `ios/` is regenerated by prebuild, fixing the file once is not enough —
 * run this AFTER every prebuild and before any archive/submit. It is wired as
 * a postbuild-safe, re-runnable step: flattening an already-flat icon is a
 * no-op, so running it twice costs nothing.
 *
 *   node scripts/flatten-ios-icons.mjs
 *
 * Exit 0 = every icon is now alpha-free (whether or not anything changed).
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const IOS = path.join(ROOT, "apps/native/ios");

if (!fs.existsSync(IOS)) {
  console.log("No apps/native/ios directory — nothing to flatten. Run `expo prebuild` first.");
  process.exit(0);
}

/** Find every AppIcon.appiconset regardless of what the app target is called. */
function findIconSets(dir) {
  const found = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const full = path.join(dir, entry.name);
    if (entry.name === "AppIcon.appiconset") found.push(full);
    else found.push(...findIconSets(full));
  }
  return found;
}

const sets = findIconSets(IOS);
if (sets.length === 0) {
  console.log("No AppIcon.appiconset found under apps/native/ios.");
  process.exit(0);
}

let changed = 0;
let checked = 0;

for (const set of sets) {
  for (const file of fs.readdirSync(set)) {
    if (!file.endsWith(".png")) continue;
    const full = path.join(set, file);
    checked++;

    const meta = await sharp(full).metadata();
    if (!meta.hasAlpha) {
      console.log(`ok    ${file}  (already RGB)`);
      continue;
    }

    // Composite onto an opaque background before dropping the channel, so a
    // genuinely translucent icon degrades predictably instead of picking up
    // whatever happened to be in the unpremultiplied RGB bytes.
    const flat = await sharp(full)
      .flatten({ background: { r: 0, g: 0, b: 0 } })
      .png({ compressionLevel: 9 })
      .toBuffer();

    fs.writeFileSync(full, flat);
    const after = await sharp(full).metadata();
    if (after.hasAlpha) {
      console.error(`FAIL  ${file}: still has an alpha channel after flattening`);
      process.exit(1);
    }
    console.log(`fixed ${file}  RGBA -> RGB`);
    changed++;
  }
}

console.log(
  `\n${checked} icon(s) checked, ${changed} flattened. ` +
    "No iOS app icon carries an alpha channel.",
);
